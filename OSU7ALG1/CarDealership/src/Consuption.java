public class Consuption {
    private double city;
    private double highway;
    private double average;

    public double getCity() {
        return city;
    }

    public double getHighway() {
        return highway;
    }

    public double getAverage() {
        return average;
    }

    public Consuption(double city, double highway, double average) {
        this.city = city;
        this.highway = highway;
        this.average = average;
    }
}

